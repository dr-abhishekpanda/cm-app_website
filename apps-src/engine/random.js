/* Seeded pseudo-random numbers for Monte Carlo p-values and bootstrap intervals, so the same data
 * always give the same answer. mulberry32: a small 32-bit generator, good enough for resampling. */
export function mulberry32(seed) {
  let s = seed >>> 0;
  return () => {
    s = (s + 0x6D2B79F5) >>> 0;
    let t = s;
    t = Math.imul(t ^ (t >>> 15), t | 1);
    t ^= t + Math.imul(t ^ (t >>> 7), t | 61);
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}
